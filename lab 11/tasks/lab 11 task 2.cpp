#include <iostream>
#include <string>
using namespace std;

int main()
{
    string firstName = "Ali";
    string lastName = "Khan";

    // Concatenate strings
    string fullName = firstName + " " + lastName;

    cout << "First Name: " << firstName << endl;
    cout << "Last Name: " << lastName << endl;
    cout << "Full Name: " << fullName << endl;

    return 0;
}
